def updated_texts(key: str, title: str, description: str | None) -> dict[str, str]:
    """Return only the fields still equal to the old built-in text."""
    if key not in METRIC_TEXTS:
        return {}
    new_title, new_description = METRIC_TEXTS[key]
    old = [texts[key] for texts in (LEGACY_METRIC_TEXTS, PREVIOUS_METRIC_TEXTS) if key in texts]
    changes = {}
    if title != new_title and any(title == old_title for old_title, _ in old):
        changes["title"] = new_title
    if (description or "") != new_description and any((description or "") == old_description for _, old_description in old):
        changes["description"] = new_description
    return changes
